import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transform } from 'esbuild';

const source = await readFile(new URL('../../src/lib/hijri.ts', import.meta.url), 'utf8');
const { code } = await transform(source, { loader: 'ts', format: 'esm' });
const { isValidGregorianDate, isValidHijriDate, hijriMonthLength, hijriToGregorian, gregorianToHijri } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);

test('Gregorian picker rejects impossible dates, empty years and century leap errors', () => {
  assert.equal(isValidGregorianDate({ year: 2024, month: 2, day: 29 }), true);
  for (const date of [{year: 2025, month: 2, day: 29}, {year: 2100, month: 2, day: 29}, {year: 2026, month: 4, day: 31}, {year: 0, month: 1, day: 1}, {year: 2026, month: 13, day: 1}]) assert.equal(isValidGregorianDate(date), false);
});

test('Hijri picker uses month length and validates before conversion', () => {
  const month = Array.from({length: 12}, (_, i) => i + 1).find(m => hijriMonthLength(1448, m) === 29);
  assert.ok(month);
  assert.equal(isValidHijriDate({year: 1448, month, day: 30}), false);
  assert.equal(isValidHijriDate({year: 1448, month, day: 29}), true);
  assert.equal(isValidHijriDate({year: 0, month: 1, day: 1}), false);
  const h = {year: 1448, month: 1, day: 1};
  const g = hijriToGregorian(h);
  assert.deepEqual(gregorianToHijri(g.year, g.month, g.day), h);
});

test('Gregorian-to-Hijri round trips sampled month boundaries from 1900 to 2100', () => {
  for (let year = 1900; year <= 2100; year++) {
    for (let month = 1; month <= 12; month++) {
      for (const day of [1, new Date(Date.UTC(year, month, 0)).getUTCDate()]) {
        const g = {year, month, day};
        const h = gregorianToHijri(year, month, day);
        assert.deepEqual(hijriToGregorian(h), g, JSON.stringify({g, h}));
      }
    }
  }
});

test('fallback tabular conversions round trip when Umm al-Qura is unavailable', async () => {
  const NativeFormatter = Intl.DateTimeFormat;
  try {
    Intl.DateTimeFormat = function(locale, options) {
      if (String(locale).includes('islamic-umalqura')) throw new RangeError('simulated unsupported calendar');
      return new NativeFormatter(locale, options);
    };
    const fallback = await import(`data:text/javascript;base64,${Buffer.from(code + '\n// fallback test').toString('base64')}`);
    assert.equal(fallback.isUmmAlQuraExact(), false);
    for (let year = 1900; year <= 2100; year += 10) {
      for (let month = 1; month <= 12; month++) {
        const g = { year, month, day: 15 };
        const h = fallback.gregorianToHijri(g.year, g.month, g.day);
        assert.deepEqual(fallback.hijriToGregorian(h), g, JSON.stringify({ g, h }));
      }
    }
  } finally {
    Intl.DateTimeFormat = NativeFormatter;
  }
});

// Ministry of Education page, directly reviewed 2026-10-29: the published
// Hijri/Gregorian pairs are independent fixtures, not generated by this engine.
test('sampled education ministry reference pairs match the local Intl engine', () => {
  const pairs = [
    [[2026, 8, 23], [1448, 3, 10]],
    [[2026, 11, 20], [1448, 6, 10]],
    [[2027, 1, 8], [1448, 7, 30]],
    [[2027, 2, 19], [1448, 9, 12]],
    [[2027, 5, 7], [1448, 12, 1]],
  ];
  for (const [[year, month, day], [hy, hm, hd]] of pairs) {
    const h = { year: hy, month: hm, day: hd };
    assert.deepEqual(gregorianToHijri(year, month, day), h);
    assert.deepEqual(hijriToGregorian(h), { year, month, day });
  }
});
